WITH RECURSIVE HOURS AS (
    SELECT 0 AS HOUR
    
    UNION ALL
    
    SELECT HOUR + 1
    FROM HOURS
    WHERE HOUR < 23
)

SELECT H.HOUR, COUNT(A.ANIMAL_ID) AS COUNT
-- COUNT(*) 로 하게 되면 NULL도 세기 때문에 ANIMAL_ID로 해야함.
FROM HOURS H LEFT JOIN ANIMAL_OUTS A
ON H.HOUR = HOUR(A.DATETIME)
GROUP BY H.HOUR
ORDER BY H.HOUR;